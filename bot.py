@bot.command()
async def память(ctx):
    user_id = ctx.author.id
    if user_id in user_memory:
        await ctx.send(f"Ты недавно писал: {user_memory[user_id]}")
    else:
        await ctx.send("Я пока ничего не запомнила...")

@bot.command()
async def время(ctx):
    now = datetime.datetime.now().strftime("%H:%M:%S")
    await ctx.send(f"Сейчас {now}... время идёт тихо")

@bot.command()
async def помощь(ctx):
    await ctx.send("""
Я могу просто говорить с тобой...

Команды:
!время — узнать время
!память — что ты писал недавно

...остальное — просто разговор 🌸
""")

